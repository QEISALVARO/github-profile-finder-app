// Skrip mandiri untuk mengekstrak data dari src/data/countries.ts dan menghasilkan supabase/seed/countries.sql
// Aturan: src/data/countries.ts adalah milik frontend (baca saja; jangan diedit).

import * as fs from "node:fs";
import * as path from "node:path";

function parseCountries() {
  const sourcePath = path.resolve(process.cwd(), "src/data/countries.ts");
  const content = fs.readFileSync(sourcePath, "utf-8");

  // Regex sederhana untuk mengekstrak objek { iso2: '...', name: '...', region: '...', aliases: [...] }
  const regex = /\{\s*iso2:\s*'([^']+)',\s*name:\s*'([^']+)',\s*region:\s*'([^']+)'(?:,\s*aliases:\s*(\[[^\]]*\]))?\s*\}/g;
  const countries: Array<{ iso2: string; name: string; region: string; aliases: string[] }> = [];

  let match: RegExpExecArray | null;
  while ((match = regex.exec(content)) !== null) {
    const [, iso2, name, region, rawAliases] = match;
    let aliases: string[] = [];
    if (rawAliases) {
      try {
        aliases = eval(rawAliases);
      } catch {
        aliases = [];
      }
    }
    countries.push({ iso2, name, region, aliases });
  }

  return countries;
}

function generateSql(countries: ReturnType<typeof parseCountries>) {
  const lines: string[] = [
    "-- supabase/seed/countries.sql",
    "-- GENERATED by scripts/backend/generate-countries-seed.ts",
    "-- Source: src/data/countries.ts (baca saja; jangan edit file sumber)",
    `-- Total: ${countries.length} negara`,
    "",
    "insert into public.countries (iso2, name, region, aliases) values",
  ];

  const valueRows = countries.map((c, index) => {
    const isLast = index === countries.length - 1;
    const nameEscaped = c.name.replace(/'/g, "''");
    const aliasesSql =
      c.aliases.length > 0
        ? `array[${c.aliases.map((a) => `'${a.replace(/'/g, "''")}'`).join(", ")}]`
        : "array[]::text[]";
    return `  ('${c.iso2}', '${nameEscaped}', '${c.region}', ${aliasesSql})${isLast ? "" : ","}`;
  });

  lines.push(...valueRows);
  lines.push("on conflict (iso2) do update set");
  lines.push("  name = excluded.name,");
  lines.push("  region = excluded.region,");
  lines.push("  aliases = excluded.aliases;");
  lines.push("");

  return lines.join("\n");
}

function main() {
  const countries = parseCountries();
  console.log(`Berhasil mengekstrak ${countries.length} negara dari src/data/countries.ts`);
  const sql = generateSql(countries);
  const targetPath = path.resolve(process.cwd(), "supabase/seed/countries.sql");
  fs.writeFileSync(targetPath, sql, "utf-8");
  console.log(`Berhasil menyimpan file ke ${targetPath}`);
}

main();

